/** 每轮都会注入：当前模式 + 该模式的工作规则。 */
export function modeBlock(mode) {
  const scene = getScene()
  if (scene?.type === 'qq') return qqBlock(scene)

  const spec = MODES[mode] || MODES.chat
  const closing =
    mode === 'operate'
      ? '这一轮结束前给三行：做了什么、结果在哪、怎么验证。'
      : '这一轮结束前给出一句「下一步」——一个具体、五分钟内能开始的动作。'
  const platform = mode === 'operate' ? `\n\n${buildPlatformBlock()}` : ''
  return `${spec.directive}${platform}

${closing}`
}

export function modeLabel(mode) {
  return (MODES[mode] || MODES.chat).label
}

